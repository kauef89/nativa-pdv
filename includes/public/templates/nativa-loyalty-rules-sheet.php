    </p>

    <h4>Como resgatar?</h4>
    <p>
        Na sua página de "Minha Conta", você pode ver seu saldo de pontos e clicar em "Resgatar prêmios" para ver a lista de produtos disponíveis para troca. Basta ter o saldo de pontos necessário e adicionar o produto ao seu carrinho.
    </p>

     <h4>Regras Gerais:</h4>
    <ol>
        <li>Os pontos são pessoais e intransferíveis.</li>
        <li>É permitido o resgate de <strong>1 (um) prêmio</strong> por pedido.</li>
        <li>Os pontos não expiram.</li>
        <li>A Nativa Delivery se reserva o direito de alterar as regras deste programa a qualquer momento.</li>
    </ol>
