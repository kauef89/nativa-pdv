    <h4>Como funciona?</h4>
    <p>
        O programa de fidelidade "Na Faixa" foi criado para recompensar nossos clientes mais leais. É simples: a cada compra, você acumula pontos que podem ser trocados por produtos deliciosos do nosso cardápio.
    </p>

    <h4>Como acumular pontos?</h4>
        <p><strong>No app:</strong>
        A cada R$ 1,00 gasto no subtotal dos seus pedidos (não inclui a taxa de entrega), você ganha <strong>8 pontos</strong>. Para pontuar, você precisa estar logado na sua conta no momento de finalizar a compra.
    </p>
    <p>
